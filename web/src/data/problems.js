function build() {
  const out = [];
  for (const [topic, rows] of Object.entries(BANK)) {
    rows.forEach(([title, difficulty, pattern, slug, freq], i) => {
      out.push({
        id: `${topic}-${i + 1}`,
        title,
        topic,
        pattern,
        difficulty,
        order: i,
        faangFreq: freq,
        url: slug ? `https://leetcode.com/problems/${slug}/` : null,
        isDrill: slug === null,
      });
    });
  }
  return out;
}

